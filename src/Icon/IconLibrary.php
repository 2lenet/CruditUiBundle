    public function prefix(): string
    {
        return match ($this) {
            self::FontAwesome => 'fa7-solid',
            self::BootstrapIcons => 'bi',
            self::Boxicons => 'bx',
            self::Flowbite => 'flowbite',
            self::Heroicons => 'heroicons',
            self::Iconoir => 'iconoir',
            self::Ionicons => 'ion',
            self::Lucide => 'lucide',
            self::MaterialDesignIcons => 'mdi',
            self::Octicons => 'octicon',
            self::Phosphor => 'ph',
            self::Tabler => 'tabler',
        };
    }

    public function suffix(): string
    {
        return match ($this) {
            self::Flowbite, self::Ionicons => '-outline',
            self::Octicons => '-24',
            default => '',
        };
    }

    /**
     * Iconify name of a logical name of the catalogue, null for a name that is not in it.
     */
    public function icon(string $name): ?string
    {
        if (!isset(IconCatalogue::ICONS[$name])) {
            return null;
        }

        $icon = self::EXCEPTIONS[$this->value][$name] ?? IconCatalogue::ICONS[$name] . $this->suffix();

        return str_contains($icon, ':') ? $icon : $this->prefix() . ':' . $icon;
    }

    /**
     * @return array<string, string> Iconify name of each logical name of the catalogue
     */
    public function icons(): array
    {
        $icons = [];
        foreach (array_keys(IconCatalogue::ICONS) as $name) {
            $icons[$name] = (string) $this->icon($name);
        }

        return $icons;
    }
